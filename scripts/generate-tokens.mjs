/**
 * Generates the SAP theme layer from @sap-theming/theming-base-content:
 *
 *   registry/styles/themes/<theme>.css   the --sap* CSS variables of each Horizon theme
 *   registry/styles/fonts.css            @font-face rules for "72" and the SAP icon fonts
 *   registry/styles/fonts/*.woff2        the font files referenced by fonts.css
 *   registry/styles/tokens.css           Tailwind v4 `@theme inline` mapping of every token
 *   registry/ui/icon/icon-glyphs.ts      glyph name -> code point maps for the icon fonts
 *
 * Naming rule (one rule for every token): drop the `sap` prefix, split camelCase and `_`,
 * lower-case, join with `-`, then prefix with `sap-` inside the Tailwind namespace.
 *   --sapButton_Hover_Background -> --color-sap-button-hover-background -> bg-sap-button-hover-background
 *   --sapContent_Shadow1         -> --shadow-sap-content-shadow1        -> shadow-sap-content-shadow1
 *   --sapElement_Height          -> --spacing-sap-element-height        -> h-sap-element-height
 *
 * Run with `pnpm tokens`. Do not edit the generated files by hand.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = dirname(require.resolve('@sap-theming/theming-base-content/package.json'));
const pkgVersion = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;
const baseLib = join(pkgDir, 'content/Base/baseLib');
const stylesDir = join(root, 'registry/styles');

const THEMES = [
    { id: 'sap_horizon', scheme: 'light', isDefault: true },
    { id: 'sap_horizon_dark', scheme: 'dark' },
    { id: 'sap_horizon_hcb', scheme: 'dark' },
    { id: 'sap_horizon_hcw', scheme: 'light' }
];

const header = (what) =>
    `/* ${what}\n * Generated by scripts/generate-tokens.mjs from @sap-theming/theming-base-content@${pkgVersion}.\n * Do not edit by hand. */\n`;

/** Reads the `:root { --sap*: ... }` block of a theme as [name, value] pairs. */
function readVariables(themeId) {
    const css = readFileSync(join(baseLib, themeId, 'css_variables.css'), 'utf8');
    const block = css.match(/^:root \{\n([\s\S]*?)^\}/m);
    if (!block) throw new Error(`No :root block in ${themeId}`);
    return [...block[1].matchAll(/^\s*(--sap[A-Za-z0-9_]+):\s*([\s\S]*?);\s*$/gm)]
        .map(([, name, value]) => [name, value.trim()])
        .filter(([name]) => !name.startsWith('--sapFontUrl_'));
}

function kebab(variable) {
    return variable
        .replace(/^--sap/, '')
        .replace(/_/g, '-')
        .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
        .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
        .replace(/-+/g, '-')
        .replace(/^-|-$/g, '')
        .toLowerCase();
}

const isColor = (v) => /^(#[0-9a-f]{3,8}|rgba?\(|hsla?\(|transparent$|color-mix\()/i.test(v);
const isLength = (v) => /^-?(\d*\.)?\d+(rem|px|em|%)$/.test(v) || v === '0';

/** Decides which Tailwind theme namespace a token belongs to (or none). */
function namespaceOf(name, value) {
    if (isColor(value)) return 'color';
    if (/TextShadow$/.test(name)) return 'text-shadow';
    if (/Shadow\d*$/.test(name) && value !== 'none') return 'shadow';
    if (/Radius$/.test(name) && isLength(value)) return 'radius';
    if (/(FontFamily|Family)$/.test(name)) return 'font';
    if (/Font.*Size$|FontSize$/.test(name) && isLength(value)) return 'text';
    if (/BorderWidth$|FocusWidth$/.test(name) && isLength(value)) return 'border-width';
    if (isLength(value)) return 'spacing';
    return null;
}

// --- themes ---------------------------------------------------------------------------------
mkdirSync(join(stylesDir, 'themes'), { recursive: true });
let referenceVars;
for (const theme of THEMES) {
    const vars = readVariables(theme.id);
    referenceVars ??= vars;
    const selector = theme.isDefault ? `:root,\n[data-sap-theme='${theme.id}']` : `[data-sap-theme='${theme.id}']`;
    const body = vars.map(([n, v]) => `    ${n}: ${v};`).join('\n');
    writeFileSync(
        join(stylesDir, 'themes', `${theme.id}.css`),
        `${header(`SAP theme "${theme.id}".`)}\n${selector} {\n    color-scheme: ${theme.scheme};\n${body}\n}\n`
    );
}

// --- fonts ----------------------------------------------------------------------------------
{
    const css = readFileSync(join(baseLib, 'sap_horizon/css_variables.css'), 'utf8');
    const faces = css.match(/@font-face \{[\s\S]*?\n\}/g) ?? [];
    mkdirSync(join(stylesDir, 'fonts'), { recursive: true });
    const copied = new Set();
    const out = faces.map((face) => {
        // keep woff2 only (supported by every evergreen browser) and point to ./fonts/
        return face.replace(/src: ([^;]*);/, (_, src) => {
            const woff2 = src.match(/url\('([^']+\.woff2)'\)/)[1];
            const file = woff2.split('/').pop();
            const from = resolve(join(baseLib, 'sap_horizon'), woff2.replace('../../../Base/baseLib/', '../'));
            if (!copied.has(file)) {
                copyFileSync(from, join(stylesDir, 'fonts', file));
                copied.add(file);
            }
            const local = src.match(/local\('([^']+)'\)/);
            return `src: url('./fonts/${file}') format('woff2')${local ? `, local('${local[1]}')` : ''};`;
        });
    });
    writeFileSync(
        join(stylesDir, 'fonts.css'),
        `${header('The "72" typeface and the SAP icon fonts.')}\n${out.join('\n')}\n`
    );
}

// --- tailwind @theme ------------------------------------------------------------------------
{
    const groups = new Map();
    for (const [name, value] of referenceVars) {
        const ns = namespaceOf(name, value);
        if (!ns) continue;
        if (!groups.has(ns)) groups.set(ns, []);
        groups.get(ns).push(`    --${ns}-sap-${kebab(name)}: var(${name});`);
    }
    const order = ['color', 'font', 'text', 'radius', 'shadow', 'text-shadow', 'spacing', 'border-width'];
    const sections = order
        .filter((ns) => groups.has(ns))
        .map((ns) => `    /* ${ns} (${groups.get(ns).length}) */\n${groups.get(ns).join('\n')}`);
    writeFileSync(
        join(stylesDir, 'tokens.css'),
        `${header('Tailwind v4 theme: every SAP token exposed as a utility value.')}` +
            `/* Tokens with no Tailwind namespace (opacity, line height, background styles, ...) are used\n` +
            ` * through the variable shorthand, e.g. opacity-(--sapContent_DisabledOpacity). */\n\n` +
            `@theme inline {\n${sections.join('\n\n')}\n}\n\n` +
            `/* border-width-sap-*: SAP border width tokens, e.g. border-width-sap-element-border-width */\n` +
            `@utility border-width-* {\n    border-width: --value(--border-width-*);\n}\n`
    );
}

// --- icon glyph maps ------------------------------------------------------------------------
{
    const fonts = {
        'SAP-icons': 'SAP-icons.json',
        'SAP-icons-TNT': 'SAP-icons-TNT.json',
        'SAP-icons-Business-Suite': 'BusinessSuiteInAppSymbols.json'
    };
    const maps = {};
    for (const [family, file] of Object.entries(fonts)) {
        const json = JSON.parse(readFileSync(join(baseLib, 'baseTheme/fonts', file), 'utf8'));
        const map = {};
        for (const [code, info] of Object.entries(json)) {
            for (const n of info.names ?? []) map[n] = { c: parseInt(code, 16), rtl: info.rtl === 'flip' };
        }
        maps[family] = map;
    }
    const lines = (map) =>
        Object.keys(map)
            .sort()
            .map((k) => `    '${k}': ${map[k].rtl ? `[0x${map[k].c.toString(16)}, 1]` : `0x${map[k].c.toString(16)}`},`)
            .join('\n');
    const dir = join(root, 'registry/ui/icon');
    mkdirSync(dir, { recursive: true });
    writeFileSync(
        join(dir, 'icon-glyphs.ts'),
        `/* Glyph name -> code point of the SAP icon fonts. A tuple [code, 1] marks a glyph that is\n` +
            ` * mirrored in right-to-left layouts.\n` +
            ` * Generated by scripts/generate-tokens.mjs from @sap-theming/theming-base-content@${pkgVersion}.\n` +
            ` * Do not edit by hand. */\n\n` +
            `export type IconGlyph = number | readonly [number, 1];\n\n` +
            `export const SAP_ICONS: Readonly<Record<string, IconGlyph>> = {\n${lines(maps['SAP-icons'])}\n};\n\n` +
            `export const SAP_ICONS_TNT: Readonly<Record<string, IconGlyph>> = {\n${lines(maps['SAP-icons-TNT'])}\n};\n\n` +
            `export const SAP_ICONS_BUSINESS_SUITE: Readonly<Record<string, IconGlyph>> = {\n${lines(maps['SAP-icons-Business-Suite'])}\n};\n`
    );
}

console.log(`Generated SAP theme layer from theming-base-content@${pkgVersion}`);
